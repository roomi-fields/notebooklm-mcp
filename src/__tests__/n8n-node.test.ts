/**
 * The n8n community node ships from this repository, so the wiring that keeps
 * it installable is held shut here.
 *
 * n8n's verification rules are specific and easy to fail silently: the package
 * name has to start with `n8n-nodes-`, the `n8n-community-node-package`
 * keyword has to be present or the package is never listed, a verified node
 * carries no runtime dependency, and one package integrates exactly one
 * service. None of that is a build error.
 */

import { describe, it, expect } from '@jest/globals';
import { readFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf-8').replace(/\r\n/g, '\n');

const NODE = 'nodes/n8n-nodes-gemini-notebook';
const pkg = JSON.parse(read(`${NODE}/package.json`));
const version = JSON.parse(read('package.json')).version as string;
const source = read(`${NODE}/nodes/NotebookLm/NotebookLm.node.ts`);

describe("the package n8n's registry will see", () => {
  it('is named so that n8n can find it at all', () => {
    // `n8n-nodes-notebooklm` existed from October 2025 and was unpublished in
    // April 2026; npm does not let an unpublished name be reused, so the name
    // carries the current product name instead — which is also the family of
    // searches we are invisible in.
    expect(pkg.name).toBe('n8n-nodes-gemini-notebook');
    expect(pkg.name.startsWith('n8n-nodes-')).toBe(true);
  });

  it('carries the keyword without which it is never listed', () => {
    expect(pkg.keywords).toContain('n8n-community-node-package');
  });

  it('declares the node and the credential n8n must load', () => {
    expect(pkg.n8n.n8nNodesApiVersion).toBe(1);
    expect(pkg.n8n.nodes).toContain('dist/nodes/NotebookLm/NotebookLm.node.js');
    expect(pkg.n8n.credentials).toContain('dist/credentials/NotebookLmApi.credentials.js');
  });

  it('carries no runtime dependency, which verification requires', () => {
    expect(pkg.dependencies).toBeUndefined();
  });

  it('tracks the server version it is a client for', () => {
    expect(pkg.version).toBe(version);
  });

  it('is MIT, with an author and a description', () => {
    expect(pkg.license).toBe('MIT');
    expect(pkg.author?.name).toBeTruthy();
    expect(pkg.description.length).toBeGreaterThan(40);
  });
});

describe('the generated node', () => {
  const spec = read('deployment/docs/openapi.yaml');
  const operations = [...spec.matchAll(/^      operationId: ([a-z_]+)$/gm)].map((m) => m[1]);
  const routes = [...source.matchAll(/^  '([a-z]+):([a-z_]+)': \{$/gm)];

  it('covers every operation in the specification', () => {
    expect(operations.length).toBe(56);
    expect([...routes.map((m) => m[2])].sort()).toEqual([...operations].sort());
  });

  it('groups them under the resources the specification tags', () => {
    const resources = new Set(routes.map((m) => m[1]));
    expect([...resources].sort()).toEqual([
      'auth',
      'content',
      'health',
      'notebook',
      'qa',
      'session',
      'source',
    ]);
  });

  it('says it is generated', () => {
    expect(source).toContain('@generated by scripts/build-n8n-node.mjs');
  });

  it('gives every parameter a unique name, so none shadows another', () => {
    // Two operations sharing `notebookId` must not produce two fields with the
    // same name: n8n keys parameters by name and the second would win.
    const names = [...source.matchAll(/^    name: '([^']+)',$/gm)].map((m) => m[1]);
    const fields = names.filter((n) => n !== 'operation' && n !== 'resource');
    expect(new Set(fields).size).toBe(fields.length);
  });

  it('does not read the two unwrapped routes through the envelope', () => {
    expect(source).toMatch(/'health:get_utcp_manual': \{[\s\S]{0,260}enveloped: false/);
    expect(source).toMatch(/'health:get_server_info': \{[\s\S]{0,260}enveloped: false/);
  });

  it('leaves an unset optional field out instead of sending it empty', () => {
    expect(source).toContain('if (value !== undefined) body[field.wire] = value');
  });

  it('is regenerated and staged by the release chain', () => {
    const scripts = JSON.parse(read('package.json')).scripts;
    expect(scripts['version:sync']).toContain('build-n8n-node.mjs');
    expect(scripts.version).toContain(`${NODE}/nodes/NotebookLm/NotebookLm.node.ts`);
    expect(read('.github/workflows/ci.yml')).toContain('npm run n8n:check');
  });
});

describe('the release that publishes it', () => {
  const release = read('.github/workflows/release.yml');

  it('publishes with provenance, which n8n requires to verify a node', () => {
    // Since 1 May 2026 n8n only verifies community nodes published from CI
    // with a provenance statement.
    expect(release).toContain('npm publish --provenance --access public');
  });

  it('publishes without storing a token', () => {
    const job = release.slice(
      release.indexOf('publish-n8n-node:'),
      release.indexOf('publish-registry:')
    );
    expect(job).not.toMatch(/secrets\.|NODE_AUTH_TOKEN/);
    expect(job).toContain("node-version: '24'");
  });

  it('refuses to publish a node whose version disagrees with the tag', () => {
    expect(release).toContain('the tag says ${TAG} and the node says ${PKG}');
  });

  it('can be started on its own, without cutting a second tag', () => {
    expect(release).toMatch(/publish-n8n-node:[\s\S]{0,400}workflow_dispatch/);
  });
});

describe('the credential', () => {
  const credential = read(`${NODE}/credentials/NotebookLmApi.credentials.ts`);

  it('asks for the server address and an optional token, and nothing Google-shaped', () => {
    expect(credential).toContain("name = 'notebookLmApi'");
    expect(credential).toMatch(/name: 'baseUrl'/);
    expect(credential).toMatch(/name: 'apiToken'/);
    // A Google password or cookie as a credential *field* cannot work: the
    // session is bound to the machine that created it. (The file says so in
    // prose, so this checks the field names rather than the text.)
    const fields = [...credential.matchAll(/^      name: '([^']+)',$/gm)].map((m) => m[1]);
    expect(fields).toEqual(['baseUrl', 'apiToken']);
  });

  it('hides the token and can be tested without a notebook', () => {
    expect(credential).toContain('password: true');
    expect(credential).toContain("url: '/health'");
  });
});
