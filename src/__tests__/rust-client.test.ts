/**
 * The Rust client ships from this repository, so the wiring that keeps it
 * honest is held shut here.
 *
 * Three things can rot silently. The crate version can drift from the server
 * version it is a client for — the same drift that left the published REST
 * specification two years behind. The release can stop publishing it. And the
 * crate can stop being built and tested at all, which is how a second
 * language turns into a second source of untested code.
 */

import { describe, it, expect } from '@jest/globals';
import { readFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf-8').replace(/\r\n/g, '\n');

const CRATE = 'crates/notebooklm-client';
const manifest = read(`${CRATE}/Cargo.toml`);
const version = JSON.parse(read('package.json')).version as string;

describe('the crate manifest', () => {
  it('carries the server version it is a client for', () => {
    expect(manifest).toContain(`\nversion = "${version}"\n`);
  });

  it('tells readers to depend on that same minor line', () => {
    const [major, minor] = version.split('.');
    expect(read(`${CRATE}/README.md`)).toContain(`notebooklm = "${major}.${minor}"`);
  });

  it('is publishable: every field crates.io requires is present', () => {
    for (const field of ['description', 'license', 'repository', 'readme', 'keywords']) {
      expect(manifest).toMatch(new RegExp(`^${field} = `, 'm'));
    }
  });

  it('publishes under the name the documentation uses', () => {
    expect(manifest).toMatch(/^name = "notebooklm"$/m);
  });
});

describe('the guards around it', () => {
  const ci = read('.github/workflows/ci.yml');
  const release = read('.github/workflows/release.yml');

  it.each([
    ['cargo fmt --check', 'formatting'],
    ['cargo clippy --all-features --all-targets -- -D warnings', 'lints'],
    ['cargo test --all-features', 'tests'],
    ['cargo package', 'packaging'],
  ])('CI runs %s, so %s cannot rot', (command) => {
    expect(ci).toContain(command);
  });

  it('releases the crate without storing a token', () => {
    expect(release).toContain('rust-lang/crates-io-auth-action');
    expect(release).toContain('cargo publish');
    // A stored token would be the thing trusted publishing exists to remove.
    expect(release).not.toMatch(/CARGO_REGISTRY_TOKEN:\s*\$\{\{\s*secrets\./);
  });

  it('refuses to publish a crate whose version disagrees with the tag', () => {
    expect(release).toContain('the tag says');
  });

  it('keeps the crate version synced by the release chain', () => {
    const sync = read('scripts/sync-version.mjs');
    expect(sync).toContain(`${CRATE}/Cargo.toml`);
    expect(sync).toContain(`${CRATE}/README.md`);
    // And staged into the version commit, or the bump would leave it behind.
    const staged = JSON.parse(read('package.json')).scripts.version as string;
    expect(staged).toContain(`${CRATE}/Cargo.toml`);
    expect(staged).toContain(`${CRATE}/README.md`);
  });
});

/**
 * The typed surface is generated, so what has to be guarded is the generator.
 *
 * It used to be seven hand-written methods, which meant a route added upstream
 * would not reach a Rust caller and nothing would notice — the defect every
 * hand-maintained copy in this repository has had: the specification frozen at
 * 1.5.9, the release list stuck at 3.0.1, the manual that described nothing.
 *
 * Now `npm run rust:check` fails when the file on disk is not what the
 * specification produces, and these hold the rest: that the surface really is
 * complete, that the synchronous twin covers the same calls, and that nobody
 * edits the generated file by hand.
 */
describe('the generated surface', () => {
  const generated = read(`${CRATE}/src/generated.rs`);
  const blocking = read(`${CRATE}/src/blocking.rs`);
  const spec = read('deployment/docs/openapi.yaml');

  const operations = [...spec.matchAll(/^      operationId: ([a-z_]+)$/gm)].map((m) => m[1]);
  const asyncCalls = [...generated.matchAll(/pub async fn (\w+)\(/g)].map((m) => m[1]);
  const blockingCalls = [...blocking.matchAll(/pub fn (\w+)\(/g)].map((m) => m[1]);

  it('covers every operation in the specification', () => {
    expect(operations.length).toBe(59);
    expect([...asyncCalls].sort()).toEqual([...operations].sort());
  });

  it('is mirrored by the synchronous twin', () => {
    for (const call of asyncCalls) {
      expect(blockingCalls).toContain(call);
    }
  });

  it('says it is generated, in both files', () => {
    expect(generated).toContain('@generated by scripts/build-rust-client.mjs');
    expect(blocking).toContain('@generated by scripts/build-rust-client.mjs');
  });

  it('keeps request types open and response types closed', () => {
    // A caller must be able to build a request; a response may gain a field
    // without that being a breaking change.
    const askRequest = generated.slice(generated.indexOf('pub struct AskRequest'));
    expect(generated.slice(0, generated.indexOf('pub struct AskRequest'))).not.toMatch(
      /#\[non_exhaustive\]\s*\npub struct AskRequest/
    );
    expect(askRequest).toContain('pub question: String');
    expect(generated).toMatch(/#\[non_exhaustive\]\npub struct AskQuestionData/);
  });

  it('reports an absent offset as absent rather than as zero', () => {
    // The trap this crate exists to avoid: a passage starting at offset zero
    // arrives with the field missing, and a zero would attribute the quotation
    // to the top of a long document.
    const item = generated.slice(generated.indexOf('pub struct SearchPassagesDataPassagesItem'));
    expect(item).toContain('pub start: Option<i64>');
  });

  it('does not read the two unwrapped routes through the envelope', () => {
    // `/` and `/utcp` answer with their own document, not with success + data.
    expect(generated).toMatch(/pub async fn get_utcp_manual[\s\S]{0,200}send_raw/);
    expect(generated).toMatch(/pub async fn get_server_info[\s\S]{0,200}send_raw/);
  });

  it('is regenerated and staged by the release chain', () => {
    const pkg = JSON.parse(read('package.json'));
    expect(pkg.scripts['version:sync']).toContain('build-rust-client.mjs');
    expect(pkg.scripts.version).toContain(`${CRATE}/src/generated.rs`);
    expect(pkg.scripts.version).toContain(`${CRATE}/src/blocking.rs`);
    expect(read('.github/workflows/ci.yml')).toContain('npm run rust:check');
  });
});

describe('what the crate promises in its own documentation', () => {
  const lib = read(`${CRATE}/src/lib.rs`);

  it('says it does not own a browser, because that is the whole design', () => {
    expect(lib).toMatch(/does not own a browser/);
  });

  it('names the current product name as well as the old one', () => {
    expect(lib).toMatch(/Gemini Notebook/);
    expect(read(`${CRATE}/README.md`)).toMatch(/Gemini Notebook/);
  });
});
